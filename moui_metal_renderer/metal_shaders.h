// The Metal Shading Language source for the direct-renderer route (ADR 0044,
// ADR 0045) as one embedded string: the library is compiled at runtime by
// `newLibraryWithSource`, so this text is data the host reads rather than code
// it links, and it is the file a fragment-shader change edits. One translation
// unit includes it (`metal_renderer.mm`), which is why it is a `static`
// definition here instead of an `extern` declaration.
//
// Four pipeline roles over one 76-byte vertex (clip position, shape-local point,
// atlas uv, gradient endpoints, two brush colours, brush kind). Everything that
// varies per draw — box size, corner radius, fill/stroke/shadow/path mode, stroke
// width, blur, shader-effect kind and amount, the layer composite parameters and
// the two brush colours — arrives as a 144-byte per-item constant, so the geometry
// buffer stays one format and no uniform buffer juggling is needed.
//
// The SDF, stroke-subtraction, shadow-spread and gradient-interpolation math is
// the same formulation `moui_wgpu_renderer/native_visual_shader.mbt` already
// pins with pixel tests, so the two diagnostic renderers agree on what a
// rounded rect, a stroke, a shadow and a gradient look like. Output is
// premultiplied because the blend state is (One, OneMinusSourceAlpha).
//
// `MOUIMetalShape` grows a composite tail (opacity, mask, filter, colour
// matrix) that only `moui_metal_composite_fragment` reads; the L1 fragments keep
// reading the two rows they already knew. `pass` is the per-pass surface-to-
// target transform: a layer renders into a texture the size of its own frame,
// so its children's clip-space positions must be rescaled and shifted, which is
// why one vertex stream can serve every pass.

#ifndef MOUI_METAL_RENDER_SHADERS_H
#define MOUI_METAL_RENDER_SHADERS_H

static const char *const kMouiMetalShaderSource =
    "#include <metal_stdlib>\n"
    "using namespace metal;\n"
    "struct MOUIMetalShape {\n"
    "  float4 box;    // width, height, radius, mode\n"
    "  float4 edge;   // stroke_width, blur_radius, effect_kind, effect_amount\n"
    "  float4 layer0; // layer_opacity, mask_kind, mask_radius, filter_kind\n"
    "  float4 layer1; // filter_amount, texel_x, texel_y, unused\n"
    "  float matrix[20];\n"
    "};\n"
    "struct MOUIMetalVertexIn {\n"
    "  float2 position [[attribute(0)]];\n"
    "  float2 local [[attribute(1)]];\n"
    "  float2 uv [[attribute(2)]];\n"
    "  float2 start [[attribute(3)]];\n"
    "  float2 end [[attribute(4)]];\n"
    "  float4 color0 [[attribute(5)]];\n"
    "  float4 color1 [[attribute(6)]];\n"
    "  float kind [[attribute(7)]];\n"
    "};\n"
    "struct MOUIMetalVertexOut {\n"
    "  float4 position [[position]];\n"
    "  float2 local;\n"
    "  float2 uv;\n"
    "  float2 start;\n"
    "  float2 end;\n"
    "  float4 color0;\n"
    "  float4 color1;\n"
    "  float kind;\n"
    "};\n"
    "vertex MOUIMetalVertexOut moui_metal_vertex(\n"
    "    MOUIMetalVertexIn in [[stage_in]],\n"
    "    constant float4& pass [[buffer(1)]]) {\n"
    "  MOUIMetalVertexOut out;\n"
    "  out.position = float4(in.position.x * pass.x + pass.z,\n"
    "                        in.position.y * pass.y + pass.w, 0.0, 1.0);\n"
    "  out.local = in.local;\n"
    "  out.uv = in.uv;\n"
    "  out.start = in.start;\n"
    "  out.end = in.end;\n"
    "  out.color0 = in.color0;\n"
    "  out.color1 = in.color1;\n"
    "  out.kind = in.kind;\n"
    "  return out;\n"
    "}\n"
    "static inline float moui_rounded_box_sdf(float2 p, float2 half_size, float radius) {\n"
    "  float r = min(radius, min(half_size.x, half_size.y));\n"
    "  float2 q = abs(p) - (half_size - float2(r, r));\n"
    "  return length(max(q, float2(0.0, 0.0))) + min(max(q.x, q.y), 0.0) - r;\n"
    "}\n"
    "static inline float4 moui_brush_color(float2 local, float2 start, float2 end,\n"
    "                                      float4 color0, float4 color1, float kind) {\n"
    "  if (kind > 0.5) {\n"
    "    float t = clamp(distance(local, start) / max(end.x, 0.0001), 0.0, 1.0);\n"
    "    return mix(color0, color1, t);\n"
    "  }\n"
    "  float2 axis = end - start;\n"
    "  float denom = max(dot(axis, axis), 0.0001);\n"
    "  float t = clamp(dot(local - start, axis) / denom, 0.0, 1.0);\n"
    "  return mix(color0, color1, t);\n"
    "}\n"
    "static inline float4 moui_effect_color(\n"
    "    float2 local, float2 size, float kind, float amount,\n"
    "    float4 color0, float4 color1) {\n"
    "  if (kind > 0.5 && kind < 1.5) {\n"
    "    // checker: square cells of min(w,h)/amount measured from the frame\n"
    "    // origin — the partition Skia raster and Sun both paint. WGPU normalizes\n"
    "    // each axis, so its cells are rectangular on a non-square frame.\n"
    "    float cell = max(min(size.x, size.y) / max(amount, 1.0), 0.0001);\n"
    "    float2 index = floor(local / cell);\n"
    "    int alt = (int(index.x) + int(index.y)) & 1;\n"
    "    return alt == 0 ? color0 : color1;\n"
    "  }\n"
    "  if (kind > 1.5 && kind < 2.5) {\n"
    "    return color0;\n"
    "  }\n"
    "  if (kind > 2.5 && kind < 3.5) {\n"
    "    // linear-gradient-debug runs across the frame's own width, whatever axis\n"
    "    // the fallback brush carried.\n"
    "    return mix(color0, color1, clamp(local.x / max(size.x, 0.0001), 0.0, 1.0));\n"
    "  }\n"
    "  // vignette: the fallback colour at the frame centre fading to black, at its\n"
    "  // own alpha, by max(w,h)/2 * max(amount, 0.8) — the radial Skia builds.\n"
    "  float radius = max(max(size.x, size.y) * 0.5 * max(amount, 0.8), 0.0001);\n"
    "  float t = clamp(length(local - size * 0.5) / radius, 0.0, 1.0);\n"
    "  return mix(color0, float4(0.0, 0.0, 0.0, color0.a), t);\n"
    "}\n"
    "static inline float moui_gaussian_tail(float x) {\n"
    "  // Half of erfc(x / sqrt(2)): the coverage a Gaussian of sigma 1 leaves at\n"
    "  // signed distance x past a hard edge -- 0.5 at the edge, 0.159 one sigma\n"
    "  // out, 0.023 two. This MSL build has no erfc, so the error function is\n"
    "  // evaluated from Abramowitz & Stegun 7.1.26, whose ~1.5e-7 bound is far\n"
    "  // below an 8-bit output.\n"
    "  float z = abs(x) * 0.70710678;\n"
    "  float t = 1.0 / (1.0 + 0.3275911 * z);\n"
    "  float poly = t * (0.254829592 + t * (-0.284496736 + t * (1.267028301 +\n"
    "                 t * (-1.536260649 + t * 1.0673548))));\n"
    "  float erf_abs = 1.0 - poly * exp(-z * z);\n"
    "  return x >= 0.0 ? 0.5 * (1.0 - erf_abs) : 0.5 * (1.0 + erf_abs);\n"
    "}\n"
    "static inline float4 moui_visual_color(\n"
    "    MOUIMetalVertexOut in, constant MOUIMetalShape& shape) {\n"
    "  if (shape.edge.z > 0.5) {\n"
    "    return moui_effect_color(in.local, shape.box.xy, shape.edge.z,\n"
    "                             shape.edge.w, in.color0, in.color1);\n"
    "  }\n"
    "  return moui_brush_color(in.local, in.start, in.end, in.color0, in.color1,\n"
    "                          in.kind);\n"
    "}\n"
    "fragment float4 moui_metal_visual_fragment(\n"
    "    MOUIMetalVertexOut in [[stage_in]],\n"
    "    constant MOUIMetalShape& shape [[buffer(0)]]) {\n"
    "  float mode = shape.box.w;\n"
    "  if (mode > 2.5) {\n"
    "    float4 color = moui_brush_color(in.local, in.start, in.end, in.color0,\n"
    "                                    in.color1, in.kind);\n"
    "    return float4(color.rgb * color.a, color.a);\n"
    "  }\n"
    "  float2 half_size = shape.box.xy * 0.5;\n"
    "  float dist = moui_rounded_box_sdf(in.local - half_size, half_size, shape.box.z);\n"
    "  float alpha = 1.0 - smoothstep(-0.5, 0.5, dist);\n"
    "  if (mode > 1.5) {\n"
    "    // The coverage a Gaussian actually leaves at a hard edge: half of erfc\n"
    "    // of the signed distance over sigma * sqrt(2), with sigma the requested\n"
    "    // blur radius -- the reading `moui_skia_renderer` hands its MaskFilter, so\n"
    "    // this is half-covered *at* the shape's edge, 0.16 one sigma past it and\n"
    "    // 0.02 two sigmas out. `shape.edge.x` carries the grow this quad was\n"
    "    // inflated by, which lets the distance field measure the shape rather than\n"
    "    // the box drawn around it; the previous 2*blur growth plus a ramp across\n"
    "    // the band painted a solid slab out to the box and fell off a cliff.\n"
    "    float sigma = max(shape.edge.y, 0.001);\n"
    "    float grow = shape.edge.x;\n"
    "    float2 inner_half = max(half_size - float2(grow, grow), float2(0.0, 0.0));\n"
    "    float inner_radius = max(shape.box.z - grow, 0.0);\n"
    "    float shape_dist = moui_rounded_box_sdf(in.local - half_size, inner_half,\n"
    "                                            inner_radius);\n"
    "    float shadow_alpha =\n"
    "        moui_gaussian_tail(shape_dist / sigma) * in.color0.a;\n"
    "    return float4(in.color0.rgb * shadow_alpha, shadow_alpha);\n"
    "  }\n"
    "  if (mode > 0.5) {\n"
    "    float stroke_width = shape.edge.x;\n"
    "    float inner_radius = max(shape.box.z - stroke_width, 0.0);\n"
    "    float2 inner_half = max(half_size - float2(stroke_width, stroke_width),\n"
    "                            float2(0.0, 0.0));\n"
    "    float inner_dist = moui_rounded_box_sdf(in.local - half_size, inner_half,\n"
    "                                           inner_radius);\n"
    "    alpha = max(alpha - (1.0 - smoothstep(-0.5, 0.5, inner_dist)), 0.0);\n"
    "  }\n"
    "  float4 color = moui_visual_color(in, shape);\n"
    "  float a = color.a * alpha;\n"
    "  return float4(color.rgb * a, a);\n"
    "}\n"
    "fragment float4 moui_metal_image_fragment(\n"
    "    MOUIMetalVertexOut in [[stage_in]],\n"
    "    constant MOUIMetalShape& shape [[buffer(0)]],\n"
    "    texture2d<float> image [[texture(0)]],\n"
    "    sampler image_sampler [[sampler(0)]]) {\n"
    "  // ImageIO hands back premultiplied RGBA, so only the run opacity scales\n"
    "  // it; multiplying rgb again would darken the image twice.\n"
    "  return image.sample(image_sampler, in.uv) * in.color0.a;\n"
    "}\n"
    "fragment float4 moui_metal_text_fragment(\n"
    "    MOUIMetalVertexOut in [[stage_in]],\n"
    "    constant MOUIMetalShape& shape [[buffer(0)]],\n"
    "    texture2d<float> coverage [[texture(0)]],\n"
    "    sampler glyph_sampler [[sampler(0)]]) {\n"
    "  float4 tinted = in.color0 * coverage.sample(glyph_sampler, in.uv);\n"
    "  return float4(tinted.rgb * tinted.a, tinted.a);\n"
    "}\n"
    "static inline float4 moui_matrix_filter(float4 c, constant float* m) {\n"
    "  float4 o;\n"
    "  o.x = dot(float4(m[0], m[1], m[2], m[3]), c) + m[4] * c.w;\n"
    "  o.y = dot(float4(m[5], m[6], m[7], m[8]), c) + m[9] * c.w;\n"
    "  o.z = dot(float4(m[10], m[11], m[12], m[13]), c) + m[14] * c.w;\n"
    "  o.w = dot(float4(m[15], m[16], m[17], m[18]), c) + m[19] * c.w;\n"
    "  return clamp(o, float4(0.0, 0.0, 0.0, 0.0), float4(1.0, 1.0, 1.0, 1.0));\n"
    "}\n"
    "fragment float4 moui_metal_composite_fragment(\n"
    "    MOUIMetalVertexOut in [[stage_in]],\n"
    "    constant MOUIMetalShape& shape [[buffer(0)]],\n"
    "    texture2d<float> source [[texture(0)]],\n"
    "    sampler layer_sampler [[sampler(0)]]) {\n"
    "  float kind = shape.layer0.w;\n"
    "  float amount = shape.layer1.x;\n"
    "  float4 sample = source.sample(layer_sampler, in.uv);\n"
    "  bool blur_x = kind > 5.5 && kind < 6.5;\n"
    "  bool blur_y = kind > 6.5 && kind < 7.5;\n"
    "  if (blur_x || blur_y) {\n"
    "    // One axis of a Gaussian whose sigma is the requested radius, sampled at"
    "    // every device pixel out to min(2 sigma, 12). Two of these passes -- the"
    "    // horizontal one writing the intermediate target the composite then reads"
    "    // -- make the group's response continuous, which the single 3x3 tap could"
    "    // not do: measured on a two-pixel bar at radius 8, that tap left six empty"
    "    // pixels and then echoed the bar. Taps stop at 12 per side, so a radius"
    "    // past 6 device pixels is truncated near 2 sigma and renormalised, which\n"
    "    // narrows the tail instead of ringing it.\n"
    "    float sigma = max(amount, 1.0);\n"
    "    // The sample budget is thirteen taps an axis, so the spacing has to grow"
    "    // The sample budget is thirteen taps an axis, so the spacing has to grow\n"
    "    // with the radius: pinned to one device pixel the kernel reached +-12 pixels\n"
    "    // whatever sigma asked for, and a sigma of 16 measured zero one sigma out\n"
    "    // where a Gaussian is at 15.9%. One step is now sigma / 6 past six pixels,\n"
    "    // so the thirteen samples cover ~2 sigma at every radius.\n"
    "    float stride = max(sigma / 6.0, 1.0);\n"
    "    int support = int(min(ceil(2.0 * sigma / stride), 12.0));\n"
    "    float2 unit = shape.layer1.yz;\n"
    "    float4 sum = float4(0.0, 0.0, 0.0, 0.0);\n"
    "    float total = 0.0;\n"
    "    for (int index = -support; index <= support; index++) {\n"
    "      float offset = float(index) * stride;\n"
    "      float weight = exp(-offset * offset / (2.0 * sigma * sigma));\n"
    "      float2 delta = blur_x ? float2(offset * unit.x, 0.0)\n"
    "                             : float2(0.0, offset * unit.y);\n"
    "      // Blurring premultiplied colour is what keeps a transparent edge from\n"
    "      // pulling black fringes; the colour-only filters below undo this.\n"
    "      sum += source.sample(layer_sampler, in.uv + delta) * weight;\n"
    "      total += weight;\n"
    "    }\n"
    "    sample = sum / total;\n"
    "  }\n"
    "  // Colour filters are defined on straight alpha, so un-premultiply, apply\n"
    "  // and re-premultiply. `moui_wgpu_renderer` filters in premultiplied space\n"
    "  // instead, so a filtered partially transparent layer can differ between\n"
    "  // the two diagnostic routes.\n"
    "  float alpha = sample.a;\n"
    "  float4 straight = float4(alpha > 0.0001 ? sample.rgb / alpha : float3(0.0, 0.0, 0.0),\n"
    "                           alpha);\n"
    "  float4 filtered = straight;\n"
    "  if (kind > 1.5 && kind < 2.5) {\n"
    "    float l = dot(straight.rgb, float3(0.2126, 0.7152, 0.0722));\n"
    "    filtered = float4(clamp(mix(float3(l, l, l), straight.rgb, amount),\n"
    "                            float3(0.0, 0.0, 0.0), float3(1.0, 1.0, 1.0)),\n"
    "                       straight.a);\n"
    "  } else if (kind > 2.5 && kind < 3.5) {\n"
    "    filtered = float4(clamp(straight.rgb + (amount - 1.0),\n"
    "                           float3(0.0, 0.0, 0.0), float3(1.0, 1.0, 1.0)),\n"
    "                      straight.a);\n"
    "  } else if (kind > 3.5 && kind < 4.5) {\n"
    "    filtered = float4(clamp((straight.rgb - 0.5) * amount + 0.5,\n"
    "                            float3(0.0, 0.0, 0.0), float3(1.0, 1.0, 1.0)),\n"
    "                       straight.a);\n"
    "  } else if (kind > 4.5 && kind < 5.5) {\n"
    "    // Bounded above on purpose: the separable blur stages are numbered 6 and\n"
    "    // 7, and an open `kind > 4.5` here ran them through the colour matrix --\n"
    "    // 25 multiply-adds and, until the identity itself was fixed, a saturated\n"
    "    // group. A blur has no business in this branch.\n"

    "    filtered = moui_matrix_filter(straight, shape.matrix);\n"
    "  }\n"
    "  float mask_alpha = 1.0;\n"
    "  if (shape.layer0.y > 0.5) {\n"
    "    float2 half_size = shape.box.xy * 0.5;\n"
    "    float dist = moui_rounded_box_sdf(in.local - half_size, half_size,\n"
    "                                       shape.layer0.z);\n"
    "    mask_alpha = 1.0 - smoothstep(-0.5, 0.5, dist);\n"
    "  }\n"
    "  float factor = clamp(shape.layer0.x * mask_alpha, 0.0, 1.0);\n"
    "  return float4(filtered.rgb * filtered.a * factor, filtered.a * factor);\n"
    "}";

#endif  // MOUI_METAL_RENDER_SHADERS_H
