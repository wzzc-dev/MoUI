#!/usr/bin/env node
import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const screenshotsDir = join(repoRoot, "resource", "screenshots");
const outPath = join(repoRoot, "website", "app", "showcase_assets.mbt");
const webAssetsDir = join(repoRoot, "website", "web_wasm", "assets", "screenshots");

async function main() {
  const files = (await readdir(screenshotsDir))
    .filter(name => /\.(png|jpe?g)$/i.test(name))
    .sort();
  if (files.length === 0) {
    throw new Error(`no screenshots under ${screenshotsDir}`);
  }
  await rm(webAssetsDir, { recursive: true, force: true });
  await mkdir(webAssetsDir, { recursive: true });
  const lines = [];
  lines.push(`///|`);
  lines.push(`/// Generated by scripts/gen-website-showcase-assets.mjs.`);
  lines.push(`/// Do not edit by hand. Original screenshots are copied`);
  lines.push(`/// from resource/screenshots into website/web_wasm/assets/screenshots.`);
  lines.push(`///|`);
  lines.push(`fn showcase_image_source(slug : String) -> String {`);
  lines.push(`  match slug {`);
  for (const name of files) {
    const slug = name.replace(/\.(png|jpe?g)$/i, "");
    await copyFile(join(screenshotsDir, name), join(webAssetsDir, name));
    lines.push(
      `    ${JSON.stringify(slug)} => ${JSON.stringify(`assets/screenshots/${name}`)}`,
    );
  }
  lines.push(`    _ => ""`);
  lines.push(`  }`);
  lines.push(`}`);

  await mkdir(join(repoRoot, "website", "app"), { recursive: true });
  await writeFile(outPath, lines.join("\n") + "\n");
  console.log(
    `wrote ${relative(repoRoot, outPath)} and copied ${files.length} screenshots`,
  );
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
