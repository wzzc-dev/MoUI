#!/usr/bin/env node

// Generate the vendored Lucide icon table consumed by `@views.lucide_icon`.
//
// Input:  resource/icons/lucide.json (checked in, ISC, extracted from
//         lucide-static; shapes converted to path `d` data).
// Output: moui/views/icon/lucide.generated.mbt
//
// Usage:
//   node scripts/generate-icon-set.mjs          # write
//   node scripts/generate-icon-set.mjs --check  # fail on drift
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { repoRoot } from "./lib/window-dependency.mjs";

const sourcePath = resolve(repoRoot, "resource/icons/lucide.json");
const outputPath = resolve(
  repoRoot,
  "moui/views/icon/lucide.generated.mbt",
);
const check = process.argv.includes("--check");

const source = JSON.parse(readFileSync(sourcePath, "utf8"));
if (source.set !== "lucide" || source.license !== "ISC") {
  console.error(
    `generate-icon-set: expected a Lucide/ISC source, got ${source.set}/${source.license}`,
  );
  process.exit(2);
}
const names = Object.keys(source.icons ?? {});
if (names.length === 0) {
  console.error("generate-icon-set: source has no icons");
  process.exit(2);
}
for (const name of names) {
  const d = source.icons[name];
  if (typeof d !== "string" || d.length === 0 || /["\\\n]/.test(d)) {
    console.error(`generate-icon-set: invalid path data for ${name}`);
    process.exit(2);
  }
}

const tableData = names
  .map(name => `${name}\t${source.icons[name]}`)
  .join("\n");
const nameData = names.join("\n");
const lines = [];
lines.push("// Generated by scripts/generate-icon-set.mjs. DO NOT EDIT.");
lines.push("//");
lines.push(
  `// Source: resource/icons/lucide.json — lucide-static v${source.version}, ISC.`,
);
lines.push("// Regenerate with: node scripts/generate-icon-set.mjs");
lines.push("");
lines.push("///|");
lines.push("/// Vendored Lucide version, for diagnostics and docs.");
lines.push("pub fn lucide_icon_version() -> String {");
lines.push(`  ${JSON.stringify(source.version)}`);
lines.push("}");
lines.push("");
lines.push("///|");
lines.push(
  "/// One `name<TAB>path` record per line; a flat string keeps the generated",
);
lines.push("/// file formatter-stable (long path literals would otherwise reflow).");
lines.push(`let lucide_icon_table_data : String = ${JSON.stringify(tableData)}`);
lines.push("");
lines.push("///|");
lines.push("let lucide_icon_table : Map[String, String] = {");
lines.push("  let table : Map[String, String] = Map([])");
lines.push("  for line in lucide_icon_table_data.split(" + JSON.stringify("\n") + ") {");
lines.push(
  "    let fields = line.split(" + JSON.stringify("\t") + ").to_array()",
);
lines.push("    if fields.length() == 2 {");
lines.push("      table.set(fields[0].to_owned(), fields[1].to_owned())");
lines.push("    }");
lines.push("  }");
lines.push("  table");
lines.push("}");
lines.push("");
lines.push("///|");
lines.push("/// Path `d` data for a Lucide icon name, or `None` when the vendored");
lines.push("/// subset does not carry it.");
lines.push("pub fn lucide_icon_path_data(name : String) -> String? {");
lines.push("  lucide_icon_table.get(name)");
lines.push("}");
lines.push("");
lines.push("///|");
lines.push("/// Every icon name in the vendored subset, in source order.");
lines.push(`let lucide_icon_name_data : String = ${JSON.stringify(nameData)}`);
lines.push("");
lines.push("///|");
lines.push("pub fn lucide_icon_names() -> Array[String] {");
lines.push(
  "  lucide_icon_name_data.split(" +
  JSON.stringify("\n") +
  ").to_array().map(name => name.to_owned())",
);
lines.push("}");
lines.push("");

const generated = lines.join("\n");

if (check) {
  let existing = "";
  try {
    existing = readFileSync(outputPath, "utf8");
  } catch {
    console.error(`generate-icon-set: missing ${outputPath}`);
    process.exit(1);
  }
  if (existing !== generated) {
    console.error(
      `generate-icon-set: ${outputPath} is stale; run node scripts/generate-icon-set.mjs`,
    );
    process.exit(1);
  }
  console.log(
    `icon set: ${names.length} ${source.set}@${source.version} icons current`,
  );
  process.exit(0);
}

writeFileSync(outputPath, generated);
console.log(
  `icon set: wrote ${names.length} ${source.set}@${source.version} icons to ${outputPath}`,
);
