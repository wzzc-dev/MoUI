#!/usr/bin/env node
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const screenshotsDir = join(repoRoot, "resource", "screenshots");
const websiteScreenshotsDir = join(screenshotsDir, "website");
const outPath = join(repoRoot, "website", "app", "showcase_assets.mbt");
const webAssetsDir = join(repoRoot, "website", "web_wasm", "assets", "screenshots");

const expectedSource = files => [
  `///|`,
  `/// Generated by scripts/gen-website-showcase-assets.mjs.`,
  `/// Do not edit by hand. Optimized WebP previews are copied`,
  `/// from resource/screenshots/website into website/web_wasm/assets/screenshots.`,
  ``,
  `///|`,
  `fn showcase_image_source(slug : String) -> String {`,
  `  match slug {`,
  ...files.map(name => {
    const slug = name.replace(/\.webp$/i, "");
    const source = JSON.stringify(`assets/screenshots/${name}`);
    const entry = `    ${JSON.stringify(slug)} => ${source}`;
    return entry.length > 80
      ? `    ${JSON.stringify(slug)} =>\n      ${source}`
      : entry;
  }),
  `    _ => ""`,
  `  }`,
  `}`,
  ``,
].join("\n");

async function main() {
  const check = process.argv.includes("--check");
  const files = (await readdir(websiteScreenshotsDir))
    .filter(name => /\.webp$/i.test(name))
    .sort();
  if (files.length === 0) {
    throw new Error(`no optimized Website screenshots under ${websiteScreenshotsDir}`);
  }
  const source = expectedSource(files);
  if (check) {
    const generated = await readFile(outPath, "utf8");
    if (generated !== source) {
      throw new Error("website showcase asset map is stale; run node scripts/gen-website-showcase-assets.mjs");
    }
    const outputFiles = (await readdir(webAssetsDir)).filter(name => /\.webp$/i.test(name)).sort();
    if (JSON.stringify(outputFiles) !== JSON.stringify(files)) {
      throw new Error("Website screenshot outputs are stale; run node scripts/gen-website-showcase-assets.mjs");
    }
    for (const name of files) {
      const [input, output] = await Promise.all([
        readFile(join(websiteScreenshotsDir, name)),
        readFile(join(webAssetsDir, name)),
      ]);
      if (!input.equals(output)) {
        throw new Error(`Website screenshot output differs for ${name}`);
      }
    }
    console.log(`verified ${files.length} optimized Website screenshots`);
    return;
  }
  await rm(webAssetsDir, { recursive: true, force: true });
  await mkdir(webAssetsDir, { recursive: true });
  for (const name of files) {
    await copyFile(join(websiteScreenshotsDir, name), join(webAssetsDir, name));
  }
  await mkdir(join(repoRoot, "website", "app"), { recursive: true });
  await writeFile(outPath, source);
  console.log(
    `wrote ${relative(repoRoot, outPath)} and copied ${files.length} optimized screenshots`,
  );
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
