#!/usr/bin/env node
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const screenshotsDir = join(repoRoot, "resource", "screenshots");
const outPath = join(repoRoot, "website", "app", "showcase_assets.mbt");

const THUMB_MAX_DIM = 480;

async function main() {
  const files = (await readdir(screenshotsDir))
    .filter(name => /\.png$/i.test(name))
    .sort();
  if (files.length === 0) {
    throw new Error(`no PNG screenshots under ${screenshotsDir}`);
  }
  const tmpDir = mkdtempSync(join(tmpdir(), "moui-showcase-"));
  const lines = [];
  lines.push(`///|`);
  lines.push(`/// Generated by scripts/gen-website-showcase-assets.mjs.`);
  lines.push(`/// Do not edit by hand. Base64-encoded downscaled screenshots`);
  lines.push(`/// from resource/screenshots/*.png.`);
  lines.push(`///|`);
  lines.push(`fn showcase_thumbnail_data_uri(slug : String) -> String {`);
  lines.push(`  match slug {`);
  for (const name of files) {
    const slug = name.replace(/\.png$/i, "");
    const tmpFile = join(tmpDir, name);
    const r = spawnSync(
      "sips",
      ["-Z", String(THUMB_MAX_DIM), join(screenshotsDir, name), "--out", tmpFile],
      { stdio: "ignore" },
    );
    if (r.status !== 0) {
      throw new Error(`sips failed for ${name}`);
    }
    const bytes = await readFile(tmpFile);
    const b64 = bytes.toString("base64");
    const uri = `data:image/png;base64,${b64}`;
    lines.push(`    ${JSON.stringify(slug)} => ${JSON.stringify(uri)}`);
  }
  lines.push(`    _ => ""`);
  lines.push(`  }`);
  lines.push(`}`);

  await mkdir(join(repoRoot, "website", "app"), { recursive: true });
  await writeFile(outPath, lines.join("\n") + "\n");
  console.log(`wrote ${relative(repoRoot, outPath)} (${files.length} entries)`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
