#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";

const usage = () => {
  console.error(
    "Usage: node scripts/generate-grapheme-break-fixtures.mjs [--input <GraphemeBreakTest-style.txt>] [--output <test.mbt>] [--helper-name <identifier>] [--test-name <name>] [--actual-kind <core-boundaries|skia-clusters>] [--check]",
  );
  process.exit(2);
};

let input = "moui/core/testdata/grapheme_break_samples.txt";
let output = "moui/core/text_grapheme_break_fixtures_wbtest.mbt";
let helperName = "assert_generated_grapheme_break_fixture";
let testName = "generated grapheme break fixture samples";
let actualKind = "core-boundaries";
let check = false;

const args = process.argv.slice(2);
for (let index = 0; index < args.length; index += 1) {
  const arg = args[index];
  if (arg === "--input") input = args[++index] ?? "";
  else if (arg === "--output") output = args[++index] ?? "";
  else if (arg === "--helper-name") helperName = args[++index] ?? "";
  else if (arg === "--test-name") testName = args[++index] ?? "";
  else if (arg === "--actual-kind") actualKind = args[++index] ?? "";
  else if (arg === "--check") check = true;
  else if (arg === "--help" || arg === "-h") usage();
  else usage();
}

if (!input || !output || !helperName || !testName) usage();
if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(helperName)) {
  throw new Error(`invalid MoonBit helper name '${helperName}'`);
}
if (!["core-boundaries", "skia-clusters"].includes(actualKind)) {
  throw new Error(`invalid actual kind '${actualKind}'`);
}

const escapeMoonString = codepoints =>
  codepoints.map(codepoint => `\\u{${codepoint.toString(16).toUpperCase()}}`).join("");

const parseFixtureLine = (line, lineNumber) => {
  const [rawBody, rawComment = ""] = line.split("#", 2);
  const body = rawBody.trim();
  if (!body) return null;
  const tokens = body.split(/\s+/);
  const codepoints = [];
  const boundaries = [];
  let pendingBoundary = null;
  let expectedBoundaryAt = 0;
  for (const token of tokens) {
    if (token === "÷" || token === "\u00f7") {
      pendingBoundary = true;
    } else if (token === "×" || token === "\u00d7") {
      pendingBoundary = false;
    } else if (/^[0-9A-Fa-f]{4,6}$/.test(token)) {
      if (pendingBoundary === null) {
        throw new Error(`${input}:${lineNumber}: codepoint '${token}' has no preceding boundary marker`);
      }
      if (pendingBoundary) boundaries.push(expectedBoundaryAt);
      const codepoint = Number.parseInt(token, 16);
      if (!Number.isFinite(codepoint) || codepoint < 0 || codepoint > 0x10ffff) {
        throw new Error(`${input}:${lineNumber}: invalid codepoint '${token}'`);
      }
      codepoints.push(codepoint);
      expectedBoundaryAt += 1;
      pendingBoundary = null;
    } else {
      throw new Error(`${input}:${lineNumber}: unsupported token '${token}'`);
    }
  }
  if (pendingBoundary === true) boundaries.push(expectedBoundaryAt);
  if (pendingBoundary === false) {
    throw new Error(`${input}:${lineNumber}: line ended with a no-break marker`);
  }
  if (codepoints.length === 0 || boundaries[0] !== 0 || boundaries.at(-1) !== codepoints.length) {
    throw new Error(`${input}:${lineNumber}: fixture must start and end with a boundary`);
  }
  const comment = rawComment.trim().replace(/\s+/g, " ");
  return {
    lineNumber,
    codepoints,
    boundaries,
    comment,
  };
};

const samples = readFileSync(input, "utf8")
  .split(/\r?\n/)
  .map(parseFixtureLine)
  .filter(Boolean);

if (samples.length === 0) {
  throw new Error(`${input}: no grapheme break samples found`);
}

const actualLines = actualKind === "core-boundaries"
  ? ["  let actual = TextGraphemeBoundaries::new(text~).boundaries()"]
  : [
    "  let actual = [0]",
    "  let mut cursor = 0",
    "  for cluster in skia_grapheme_cluster_texts(text) {",
    "    cursor += cluster.to_array().length()",
    "    actual.push(cursor)",
    "  }",
  ];

const generated = `///| Generated by scripts/generate-grapheme-break-fixtures.mjs.
///| Source fixture: ${input}

///|
fn ${helperName}(
  text : String,
  expected : Array[Int],
  label : String,
) -> Unit raise {
${actualLines.join("\n")}
  if actual.length() != expected.length() {
    fail(
      "\\{label}: expected \\{expected.length()} grapheme boundaries, got \\{actual.length()}",
    )
  }
  for index in 0..<expected.length() {
    inspect(actual[index], content="\\{expected[index]}")
  }
}

///|
test "${testName}" {
${samples.map(sample => {
  const text = escapeMoonString(sample.codepoints);
  const expected = sample.boundaries.join(", ");
  const label = sample.comment || `line ${sample.lineNumber}`;
  return `  ${helperName}("${text}", [${expected}], "${label}")`;
}).join("\n")}
}
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch (error) {
    console.error(`${output}: ${error.message}`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error(`${output}: generated grapheme break fixture test is out of date`);
    process.exit(1);
  }
  console.log(`${output}: ok`);
} else {
  writeFileSync(output, generated);
  console.log(`wrote ${output}`);
}
