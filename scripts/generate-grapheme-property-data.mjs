#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";

const usage = () => {
  console.error(
    [
      "Usage: node scripts/generate-grapheme-property-data.mjs",
      "  --grapheme-property <GraphemeBreakProperty.txt>",
      "  --emoji-data <emoji-data.txt>",
      "  [--output <text_grapheme_data.mbt>]",
      "  [--check]",
      "",
      "The default output is moui/core/text_grapheme_data.mbt.",
    ].join("\n"),
  );
  process.exit(2);
};

let graphemeProperty = "";
let emojiData = "";
let output = "moui/core/text_grapheme_data.mbt";
let check = false;

const args = process.argv.slice(2);
for (let index = 0; index < args.length; index += 1) {
  const arg = args[index];
  if (arg === "--grapheme-property") graphemeProperty = args[++index] ?? "";
  else if (arg === "--emoji-data") emojiData = args[++index] ?? "";
  else if (arg === "--output") output = args[++index] ?? "";
  else if (arg === "--check") check = true;
  else if (arg === "--help" || arg === "-h") usage();
  else usage();
}

if (!graphemeProperty || !emojiData || !output) usage();

const parseCodepoint = (value, source, lineNumber) => {
  if (!/^[0-9A-Fa-f]{4,6}$/.test(value)) {
    throw new Error(`${source}:${lineNumber}: invalid codepoint '${value}'`);
  }
  const codepoint = Number.parseInt(value, 16);
  if (!Number.isFinite(codepoint) || codepoint < 0 || codepoint > 0x10ffff) {
    throw new Error(`${source}:${lineNumber}: invalid codepoint '${value}'`);
  }
  return codepoint;
};

const parseRange = (value, source, lineNumber) => {
  const parts = value.trim().split("..");
  if (parts.length === 1) {
    const codepoint = parseCodepoint(parts[0], source, lineNumber);
    return { start: codepoint, end: codepoint };
  }
  if (parts.length === 2) {
    const start = parseCodepoint(parts[0], source, lineNumber);
    const end = parseCodepoint(parts[1], source, lineNumber);
    if (end < start) {
      throw new Error(`${source}:${lineNumber}: range end precedes start`);
    }
    return { start, end };
  }
  throw new Error(`${source}:${lineNumber}: invalid range '${value}'`);
};

const parsePropertyRanges = (source, wantedProperties) => {
  const wanted = new Set(wantedProperties);
  const ranges = Object.fromEntries(wantedProperties.map(property => [property, []]));
  readFileSync(source, "utf8")
    .split(/\r?\n/)
    .forEach((line, lineIndex) => {
      const lineNumber = lineIndex + 1;
      const [rawBody] = line.split("#", 2);
      const body = rawBody.trim();
      if (!body) return;
      const fields = body.split(";").map(field => field.trim());
      if (fields.length < 2) {
        throw new Error(`${source}:${lineNumber}: expected '<range>; <property>'`);
      }
      const property = fields[1];
      if (!wanted.has(property)) return;
      ranges[property].push(parseRange(fields[0], source, lineNumber));
    });
  return ranges;
};

const mergeRanges = ranges => {
  const sorted = [...ranges].sort((left, right) =>
    left.start === right.start ? left.end - right.end : left.start - right.start
  );
  const merged = [];
  for (const range of sorted) {
    const previous = merged.at(-1);
    if (previous && range.start <= previous.end + 1) {
      previous.end = Math.max(previous.end, range.end);
    } else {
      merged.push({ ...range });
    }
  }
  return merged;
};

const moonHex = value => `0x${value.toString(16).toUpperCase().padStart(4, "0")}`;

const expressionForRanges = ranges => {
  const merged = mergeRanges(ranges);
  if (merged.length === 0) return ["  false"];
  return merged.map((range, index) => {
    const suffix = index === merged.length - 1 ? "" : " ||";
    if (range.start === range.end) {
      return `  codepoint == ${moonHex(range.start)}${suffix}`;
    }
    return `  (codepoint >= ${moonHex(range.start)} && codepoint <= ${moonHex(range.end)})${suffix}`;
  });
};

const functionForRanges = (name, ranges) => `///|
fn ${name}(codepoint : Int) -> Bool {
${expressionForRanges(ranges).join("\n")}
}
`;

const graphemePropertyNames = [
  "CR",
  "LF",
  "Control",
  "Prepend",
  "Extend",
  "SpacingMark",
  "Regional_Indicator",
  "ZWJ",
];

const graphemeRanges = parsePropertyRanges(graphemeProperty, graphemePropertyNames);
const emojiRanges = parsePropertyRanges(emojiData, ["Extended_Pictographic"]);

const generated = `///| Generated by scripts/generate-grapheme-property-data.mjs.
///| Sources: Unicode 17.0.0 GraphemeBreakProperty.txt and emoji-data.txt.
///| Unicode data terms: https://www.unicode.org/terms_of_use.html

${[
  functionForRanges("unicode_grapheme_is_cr_17_0", graphemeRanges.CR),
  functionForRanges("unicode_grapheme_is_lf_17_0", graphemeRanges.LF),
  functionForRanges("unicode_grapheme_is_control_17_0", graphemeRanges.Control),
  functionForRanges("unicode_grapheme_is_prepend_17_0", graphemeRanges.Prepend),
  functionForRanges("unicode_grapheme_is_extend_17_0", graphemeRanges.Extend),
  functionForRanges(
    "unicode_grapheme_is_spacing_mark_17_0",
    graphemeRanges.SpacingMark,
  ),
  functionForRanges(
    "unicode_grapheme_is_regional_indicator_17_0",
    graphemeRanges.Regional_Indicator,
  ),
  functionForRanges("unicode_grapheme_is_zwj_17_0", graphemeRanges.ZWJ),
  functionForRanges(
    "unicode_emoji_is_extended_pictographic_17_0",
    emojiRanges.Extended_Pictographic,
  ),
].join("\n")}
`;

if (check) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch (error) {
    console.error(`${output}: ${error.message}`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error(`${output}: generated Unicode grapheme property data is out of date`);
    process.exit(1);
  }
  console.log(`${output}: ok`);
} else {
  writeFileSync(output, generated);
  console.log(`wrote ${output}`);
}
